/**
 * THE DESK'S FORESIGHT, v2 - how far ahead each tier can actually see.
 *
 * v1 rolled a die weighted by tier when the house was full TONIGHT. It could
 * not be wrong for the right reasons, because it could not see tomorrow.
 *
 * Now a phone call is an enquiry for a FUTURE day, and what separates the tiers
 * is the question they think to ask:
 *
 *   Trainee       Checks the arrival night. Will cheerfully sell night one of a
 *                 three-night stay and hand you a relocation on night two.
 *   Experienced   Checks every night of the stay. Sound, but will sell the last
 *                 room in the house to a one-nighter without a second thought.
 *   Head of dept. Checks the span AND keeps a room back. Selling your last room
 *                 to a short stay is how you turn away the long one that rings
 *                 an hour later, and this is the tier that has learned that.
 *
 * NOTE ON THE LAST ONE: this is a BUFFER rule, not the full stranding check in
 * domain/Calendar.js. The day simulation carries a per-night count of free
 * rooms rather than the whole forward book - a Calendar cloned on every tick
 * would be far too expensive on a phone. It produces the same behaviour in the
 * common case and it is deliberately described here as what it is.
 */
export const DESK_TIER = {
  1: { span: false, buffer: 0, label: "checks the arrival night" },
  2: { span: true, buffer: 0, label: "checks the whole stay" },
  3: { span: true, buffer: 1, label: "checks the stay and keeps a room back" },
};

/**
 * Free rooms on every night an enquiry would occupy, given the day's running
 * forward ledger. `forwardFree[i]` is rooms free `i` days from today.
 */
export function nightsFree(shift, enquiry) {
  const out = [];
  for (let n = 0; n < enquiry.nights; n += 1) {
    const at = enquiry.inDays + n;
    out.push(shift.forwardFree ? (shift.forwardFree[at] ?? 0) : 1);
  }
  return out;
}

/**
 * Should this enquiry be taken? Returns the reason either way, because "we
 * turned it away" and "we had nowhere to put them" are different sentences and
 * the results card should be able to say which.
 */
export function judgeEnquiry(shift, enquiry, tier) {
  const desk = DESK_TIER[tier] ?? DESK_TIER[1];
  const free = nightsFree(shift, enquiry);
  const checked = desk.span ? free : free.slice(0, 1);
  const worst = Math.min(...checked);

  if (worst <= 0) return { accept: false, reason: "no_room" };
  if (desk.buffer > 0 && worst <= desk.buffer) {
    return { accept: false, reason: "held_back" };
  }
  return { accept: true, reason: "ok" };
}

/** An enquiry made on the phone: a stay, some days out. */
export function makeEnquiry(shift) {
  // Most enquiries are for the next few days; a few are further out. That skew
  // is what makes the forward book fill unevenly and worth looking at.
  const roll = nextRandom(shift);
  const inDays = roll < 0.35 ? 0 : 1 + Math.floor(nextRandom(shift) * 6);
  return {
    inDays,
    nights: pickWeighted(shift, NIGHT_MIX).nights,
    guests: pickWeighted(shift, PARTY_MIX).guests,
  };
}

