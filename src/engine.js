/**
 * Hotel Career - pure operations simulation.
 *
 * No DOM, no wall clock, no unseeded randomness: a shift is a function of
 * (level, seed, decisions), so it replays exactly and can be balance-swept
 * headlessly.
 *
 * THREE SYSTEMS, and the tension between them is the game:
 *
 *  1. TASKS. Every job - checking in, walking a guest up with their bags,
 *     turning a room, fixing one, answering the phone - is a task with a
 *     duration, a deadline and a payoff. The player does ONE at a time by hand.
 *
 *  2. STAFF. Hired staff work tasks of their own role automatically. They are
 *     slower than the owner, they have TIERS, and they EXHAUST: energy drains
 *     per job and recovers only while idle. A tired brigade is how a good
 *     roster still loses a shift.
 *
 *  3. THE BOOK. Guests arrive against reservations, not at random. Answering
 *     the phone sells another room - and is the main way you OVERBOOK yourself,
 *     because a booking you cannot house costs far more than the room earned.
 *
 * Money is net: takings minus the day's wages. Staff are a real cost.
 */

