/**
 * CASH OR CARD, and why the distinction is not decoration.
 *
 * The operator's point: "There must be cash (received from the guests in the
 * hotel) and card, bank transactions which get right in the bank."
 *
 * A hotel takes money in two forms and they behave completely differently. Cash
 * is in the till the moment the guest hands it over - it is yours, today, and
 * it is what a small hotel actually lives on. Card settles to the bank, and the
 * bank is what pays a contractor: nobody builds you a restaurant for a bag of
 * notes.
 *
 * The share paid in cash falls sharply with class, which is true and is also a
 * quiet piece of progression: a 1-star guesthouse runs on cash, and by 5 stars
 * almost everything is on a card and everything you own is financed from the
 * bank. UNVERIFIED - these are shaped from practice, not measured.
 */
export const CASH_SHARE_BY_CLASS = { 1: 0.62, 2: 0.48, 3: 0.30, 4: 0.16, 5: 0.08 };

/** F&B is cash-heavier than the front desk everywhere in the world. */
export const FNB_CASH_BONUS = 0.15;

export function cashShare(stars, { fnb = false } = {}) {
  const base = CASH_SHARE_BY_CLASS[stars] ?? CASH_SHARE_BY_CLASS[1];
  return clamp(base + (fnb ? FNB_CASH_BONUS : 0), 0, 0.95);
}

/**
 * Split a sum into what lands in the till and what lands in the bank.
 * Rounded so the two always add back to exactly the amount taken.
 */
export function splitPayment(amount, stars, options = {}) {
  const cash = Math.round(amount * cashShare(stars, options));
  return { cash, card: Math.round(amount) - cash };
}

/** A 5-star dinner cheque is not a 1-star's. Spend scales with the house. */
export const CLASS_SPEND_FACTOR = { 1: 0.7, 2: 0.85, 3: 1, 4: 1.45, 5: 2.1 };

/**
 * ...and so does what it costs to put on the plate, but NOT by the same curve.
 * A 5-star charges three times a 1-star and spends rather less than three times
 * as much on the ingredients: that widening gap is most of why the class ladder
 * is worth climbing, and it is a real feature of the trade rather than a bonus.
 */
export const CLASS_PLATE_FACTOR = { 1: 0.65, 2: 0.8, 3: 1, 4: 1.45, 5: 2.0 };

/** Cost of goods on the drink half of the cheque. The famous number. */
export const POUR_COST = 0.22;

/**
 * Of the food you prepped and did not sell, how much is actually lost. Some of
 * it goes into tomorrow's stock or the staff meal; the rest is a bin.
 */
export const PREP_WASTE = 0.4;

/** Party size when we do not know it - guests already in house at the open. */
export const AVERAGE_PARTY = 2.1;

/** Heads sleeping in the house right now. */
export function guestsInHouse(shift) {
  return shift.rooms.reduce((total, room) => {
    if (room.state !== ROOM.OCCUPIED || !room.inHouse) return total;
    const guest = shift.guests.find((g) => g.id === room.guestId);
    return total + (guest ? guest.guests : AVERAGE_PARTY);
  }, 0);
}

/**
 * The heads F&B actually trades against - the FULLEST the house got today, not
 * whoever happens to be left at the final tick.
 *
 * This was a real bug with a real symptom. Dinner was being priced against the
 * house AFTER the morning checkouts and before the evening arrivals had all
 * come in, so a thirty-room hotel served a twelve-room restaurant and the
 * kitchen's capacity never bound anything. Service happens in the evening, with
 * the house as full as it is going to get, and this is the honest proxy for
 * that in a simulation that runs one compressed day.
 */
export function coversBase(shift) {
  return Math.max(shift.peakInHouse || 0, guestsInHouse(shift));
}

/** How many of each trade are on the payroll for the day. */
export function brigadeCount(staff, role) {
  return staff.filter((person) => person.role === role).length;
}

/** The cheque a house of this class can honestly ask for a cover here. */
export function fairCheque(outlet, stars) {
  const spec = OUTLET_SPEC[outlet];
  if (!spec) return 0;
  return Math.round(spec.fairCheque * (CLASS_SPEND_FACTOR[stars] || 1));
}

/** What the food on one cover costs to produce in a house of this class. */
export function plateCost(outlet, stars) {
  const spec = OUTLET_SPEC[outlet];
  if (!spec) return 0;
  return spec.plateCost * (CLASS_PLATE_FACTOR[stars] || 1);
}

/**
 * Covers the brigade can actually serve tonight, and which side of the pass is
 * the binding constraint - because "hire another waiter" and "hire another
 * chef" are different answers and the player deserves to be told which.
 */
export function outletCapacity(outlet, staff) {
  const spec = OUTLET_SPEC[outlet];
  if (!spec) return { covers: 0, limitedBy: null, missing: [] };

  const roles = Object.keys(spec.brigade);
  // The spa has no brigade modelled at all, so nothing constrains it.
  if (roles.length === 0) return { covers: Infinity, limitedBy: null, missing: [] };

  const missing = roles.filter((role) => brigadeCount(staff, role) === 0);
  if (missing.length > 0) return { covers: 0, limitedBy: null, missing };

  let covers = Infinity;
  let limitedBy = null;
  for (const role of roles) {
    const able = brigadeCount(staff, role) * spec.brigade[role];
    if (able < covers) { covers = able; limitedBy = role; }
  }
  // `limitedBy` names the TRADE that runs out, so the F&B screen can say
  // "hire another waiter" instead of "capacity reached".
  return { covers, limitedBy, missing: [] };
}

/**
 * What the menu price does to the number of guests who eat in.
 *
 * Deliberately gentler than the room-rate curve: these people are already in the
 * building and some of them are not going to walk out into the rain for a
 * cheaper dinner. But it bites hardest in the restaurant, which is the one
 * outlet a guest can genuinely substitute.
 */
export function cheque(outlet, price, fair) {
  const spec = OUTLET_SPEC[outlet];
  const ratio = price / Math.max(1, fair);
  const e = spec ? spec.elasticity : 0.5;
  return clamp(1 + e - e * ratio * 1.02, 0.15, 1 + e * 0.55);
}

/**
 * One outlet's night, in the order a restaurant P&L is actually read.
 *
 * `staff` is the whole day's roster - the brigade is drawn from it, and a chef
 * who cooks breakfast, dinner AND the room-service trolley is ONE wage split
 * across the three, not three wages. That attribution is what lets the player
 * see whether the trolley is worth running at all.
 */
export function outletNight(outlet, { heads, stars, price = null, staff = [], wageShare = {} }) {
  const spec = OUTLET_SPEC[outlet];
  const fair = fairCheque(outlet, stars);
  const cheque_ = price === null || price === undefined ? fair : Math.round(price);
  const capacity = outletCapacity(outlet, staff);
  const plate = plateCost(outlet, stars);

  const wanted = heads * spec.capture * cheque(outlet, cheque_, fair);
  const served = Math.max(0, Math.min(wanted, capacity.covers));
  const turnedAway = Math.max(0, wanted - served);

  // The kitchen preps for the covers it expects at its NORMAL price, then finds
  // out what it actually sold. Pricing yourself out of your own dining room is
  // what fills the bin - understaffing is punished by the turnaways above, not
  // twice over here.
  const prepped = Math.min(capacity.covers, heads * spec.capture);
  const waste = capacity.covers === 0 ? 0
    : Math.max(0, prepped - served) * plate * PREP_WASTE;

  const revenue = served * cheque_;
  const foodRevenue = revenue * (1 - spec.bevShare);
  const drinkRevenue = revenue * spec.bevShare;
  const foodCost = served * plate + waste;
  const drinkCost = drinkRevenue * POUR_COST;
  const upkeep = FACILITY_UPKEEP[outlet] || 0;
  const labour = wageShare[outlet] || 0;

  return {
    outlet,
    open: capacity.covers > 0,
    missing: capacity.missing,
    limitedBy: capacity.limitedBy,
    capacity: capacity.covers === Infinity ? null : Math.round(capacity.covers),
    covers: Math.round(served),
    turnedAway: Math.round(turnedAway),
    cheque: cheque_,
    fairCheque: fair,
    revenue: Math.round(revenue),
    foodRevenue: Math.round(foodRevenue),
    drinkRevenue: Math.round(drinkRevenue),
    foodCost: Math.round(foodCost),
    drinkCost: Math.round(drinkCost),
    waste: Math.round(waste),
    labour: Math.round(labour),
    upkeep,
    cost: Math.round(foodCost + drinkCost + upkeep + labour),
    net: Math.round(revenue - foodCost - drinkCost - upkeep - labour),
    // The two percentages an operator reads first, and never the same one twice.
    foodCostPct: foodRevenue > 0 ? Math.round((foodCost / foodRevenue) * 100) : null,
    pourCostPct: drinkRevenue > 0 ? Math.round((drinkCost / drinkRevenue) * 100) : null,
  };
}

/**
 * Split each F&B wage across the outlets that person actually worked, weighted
 * by covers, so one chef cooking three services is one wage and the trolley
 * carries its fair share of it rather than looking free.
 */
function shareFnbWages(shift, load) {
  const share = {};
  for (const person of shift.staff) {
    if (!isFnbRole(person.role)) continue;
    const worked = Object.keys(load).filter((outlet) =>
      outletBrigade(outlet).includes(person.role));
    const total = worked.reduce((sum, outlet) => sum + load[outlet], 0);
    for (const outlet of worked) {
      const weight = total > 0 ? load[outlet] / total : 1 / Math.max(1, worked.length);
      share[outlet] = (share[outlet] || 0) + person.wage * weight;
    }
  }
  return share;
}

/** Payroll for the outlets alone - charged inside the F&B P&L, not twice. */
export function fnbWages(shift) {
  return shift.staff.reduce((total, p) => total + (isFnbRole(p.role) ? p.wage : 0), 0);
}

/**
 * The day's trade from every facility that is built, priced against who is
 * actually in the house and who is actually on the brigade.
 *
 * Returns the gross, every cost line separately, and a per-outlet breakdown, so
 * the results card can show WHERE the money came from rather than one lump the
 * player has to take on trust.
 */
export function facilityTrade(shift) {
  const heads = coversBase(shift);
  const menu = shift.menu || {};
  const breakdown = {};

  // Two passes: the first works out how busy each outlet was so the second can
  // split the brigade's wages across them honestly.
  const load = {};
  for (const facility of shift.facilities) {
    if (!OUTLET_SPEC[facility]) continue;
    const dry = outletNight(facility, { heads, stars: shift.stars, price: menu[facility], staff: shift.staff });
    load[facility] = dry.covers;
  }
  const wageShare = shareFnbWages(shift, load);

  let revenue = 0;
  let cogs = 0;
  let upkeep = 0;
  let labour = 0;
  let turnedAway = 0;
  let openOutlets = 0;
  let shutOutlets = 0;
  let goodwill = 0;

  for (const facility of shift.facilities) {
    if (!OUTLET_SPEC[facility]) {
      // The laundry and the concierge desk earn nothing directly and cost every
      // day. They are still a line on the P&L.
      const keep = FACILITY_UPKEEP[facility] || 0;
      upkeep += keep;
      breakdown[facility] = {
        outlet: facility, open: true, trades: false, revenue: 0, cost: keep,
        net: -keep, covers: 0, upkeep: keep, labour: 0, turnedAway: 0, missing: [],
      };
      continue;
    }
    const night = outletNight(facility, {
      heads, stars: shift.stars, price: menu[facility], staff: shift.staff, wageShare,
    });
    revenue += night.revenue;
    cogs += night.foodCost + night.drinkCost;
    upkeep += night.upkeep;
    labour += night.labour;
    turnedAway += night.turnedAway;
    if (night.open) openOutlets += 1; else shutOutlets += 1;

    // WHAT THE DINING ROOM DID TO THE HOTEL'S NAME.
    //
    // Measured as the SHARE of would-be diners refused rather than the count,
    // so it means the same thing in an eight-room house and a thirty-room one.
    // An outlet that served everyone who wanted it is a small credit; one that
    // turned people away is a complaint however much money it took; one you
    // built and never staffed is a door with a sign on it.
    const wanted = night.covers + night.turnedAway;
    const refused = wanted > 0 ? night.turnedAway / wanted : 0;
    goodwill += !night.open ? -2.5 : refused < 0.05 ? 1.5 : -12 * refused;

    breakdown[facility] = { ...night, trades: true, refusedShare: Math.round(refused * 100) };
  }

  const satisfaction = clamp(goodwill, -16, 5);

  return {
    revenue: Math.round(revenue),
    cogs: Math.round(cogs),
    upkeep,
    labour: Math.round(labour),
    turnedAway: Math.round(turnedAway),
    net: Math.round(revenue - cogs - upkeep - labour),
    satisfaction: Math.round(satisfaction * 10) / 10,
    breakdown,
  };
}

