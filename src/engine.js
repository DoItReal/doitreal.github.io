export function createShift(level, seed, options = {}) {
  const { roster = null, price = null, rating = 3.5 } = options;
  const base = levelConfig(level);

  /**
   * THE DAY IS THE SESSION. There is no separate shift timer.
   *
   * This was the single most confusing thing about the first v3 build: the day
   * on the clock lasted ten minutes, but the FLOOR ran on the old 145-second
   * shift length and then declared the day over. Two notions of "day end", one
   * of which was exactly the two-minute day the whole rewrite existed to kill.
   *
   * So the day's work runs the full length of the day, and everything paced
   * against the old duration is stretched to match: arrivals already spread
   * across `durationSec`, but walk-ins are a per-second probability and the
   * phone had a fixed cadence, so both would have fired four times as often or
   * bunched into the first two minutes.
   */
  /**
   * WHICH DAY THIS IS. The timetable depends on it - day 1 opens at 08:00, every
   * day after runs midnight to midnight. See Schedule.js.
   */
  const today = options.today ?? 1;
  const durationSec = Math.max(30, Math.round(options.durationSec ?? base.durationSec));
  const stretch = durationSec / base.durationSec;
  const config = {
    ...base,
    // THE TEACHING ARC OVERRIDES THE RANK. See ONBOARDING_DAYS - without this,
    // days 3, 4 and 5 could not teach the departments they exist to teach.
    ...onboardingDay(options.today ?? null),
    durationSec,
    dayStretch: stretch,
    walkInChance: base.walkInChance / stretch,
  };
  const random = mulberry32(seed + level * 7717);
  staffSeq = 0;

  // THE HOUSE IS THE PROPERTY'S, NOT THE LEVEL'S.
  //
  // Room count used to be a fixed property of the level, which is why the bank
  // had nothing to buy: every day was played in the same building. It now comes
  // from what the player has actually built and paid for (see property.js), and
  // the level config is only the fallback for a standalone shift.
  const roomCount = Math.max(1, Math.round(options.rooms ?? config.rooms));
  const upgradedRooms = Math.min(roomCount, Math.max(0, options.upgradedRooms ?? 0));

  /**
   * THE PROPERTY'S ACTUAL ROOMS, when it has them.
   *
   * `options.house` is a list of domain `Room` objects - real doors with
   * numbers, types, views and floors. When it is absent the day falls back to
   * the old flat house of identical rooms, which is what keeps every existing
   * test and every standalone shift working while the migration finishes.
   */
  const house = Array.isArray(options.house) && options.house.length >= roomCount
    ? options.house.slice(0, roomCount)
    : null;

  /**
   * Guests already asleep upstairs - bookings from earlier days whose stay
   * covers today. Null means "no book", and the day falls back to a seeded
   * occupancy roll exactly as before.
   */
  const residents = Array.isArray(options.inHouse) ? options.inHouse : null;

  // Stars are certified against a checklist, not handed out by level. With no
  // restaurant and no bar built, the property is honestly a 1-star.
  const facilities = options.facilities ?? config.facilities ?? [];
  // The owner works a department too, and an inspector counts it: nobody rules
  // that reception is unstaffed because the person behind the desk owns the
  // building. Without this a level-1 house is unrated rather than an honest
  // 1-star. It is NOT counted for offline coverage - see property.js.
  const staffRoles = (roster ?? config.hired).map((s) => s.role);
  if (config.role) staffRoles.push(config.role);
  const certification = evaluateStars({
    rooms: roomCount, facilities, staff: staffRoles, rating,
  });
  const stars = certification.stars;
  const fair = fairRate(stars, rating);
  const roomRate = price === null ? fair : Math.round(price);
  const demand = config.pricingEnabled ? demandFactor(roomRate, fair) : 1;
  const expectation = config.pricingEnabled ? expectationFor(roomRate, fair) : 0.55;
  // The book scales with the house. Without this, building rooms would LOWER
  // occupancy and the facility economy would punish the player for investing.
  const houseScale = roomCount / config.rooms;
  const bookings = Math.max(3, Math.round(config.reservations * demand * houseScale));

  const staff = roster
    ? roster.map((s) => ({ ...makeStaff(s.role, s.tier) }))
    : config.hired.map((h) => makeStaff(h.role, h.tier));

  // The book: today's ARRIVALS, known in advance. Each is a stay of several
  // nights by a party of a certain size - not a one-night single.
  const scratch = { rngState: Math.floor(random() * 4294967296) };
  const reservations = [];

  /**
   * TODAY'S ARRIVALS COME FROM THE FORWARD BOOK when there is one.
   *
   * These are reservations made on earlier days for THIS day - which is what a
   * hotel's arrivals list actually is, and what makes "is 402 free on the 14th"
   * a question with consequences. Without a book, the day invents its own
   * arrivals as it always did, which is what keeps every standalone shift and
   * every existing test working.
   */
  const booked = Array.isArray(options.arrivals) ? options.arrivals : null;
  if (booked) {
    booked.forEach((arrival, i) => {
      reservations.push({
        id: arrival.id ?? i + 1,
        dueAt: arrivalTime(i, booked.length, today, config.durationSec, random),
        source: "book",
        nights: arrival.nights ?? 1,
        guests: arrival.guests ?? 2,
        bookedType: arrival.requestedType ?? arrival.bookedType ?? null,
        /** The forward booking this arrival belongs to, for the write-back. */
        bookingId: arrival.id ?? null,
        arrived: false,
        housed: null,
      });
    });
  } else {
    for (let i = 0; i < bookings; i += 1) {
      reservations.push({
        id: i + 1,
        dueAt: arrivalTime(i, bookings, today, config.durationSec, random),
        source: "book",
        nights: pickWeighted(scratch, NIGHT_MIX).nights,
        guests: pickWeighted(scratch, PARTY_MIX).guests,
        // What they booked - a type, not a door. The desk decides the door.
        bookedType: house ? bookedTypeFor(house, random()) : null,
        bookingId: null,
        arrived: false,
        housed: null,
      });
    }
  }
  reservations.sort((a, b) => a.dueAt - b.dueAt);

  return {
    level, seed, config,
    /** The day on the timeline this shift is. Schedule.js needs it. */
    today,
    stars, certification, facilities,
    /**
     * What the player charges per cover in each outlet, keyed by FACILITY. An
     * outlet missing from here trades at its fair cheque, which is what a new
     * restaurant opens at until somebody moves the price.
     */
    menu: { ...(options.menu || {}) },
    /** What the desk does with a better room than the guest booked. */
    upsellPolicy: options.upsellPolicy ?? UPSELL_POLICY.PROTECT,
    roomRate, fairRate: fair, expectation, demand,
    reviews: [],
    incomingRating: rating,
    time: 0, over: false,
    rngState: Math.floor(random() * 4294967296),
    nextId: 1000,
    // The house does not start empty. Most rooms hold guests part-way through a
    // stay, and some of those leave this morning - which is where the day's
    // housekeeping comes from.
    roomCount,
    upgradedRooms,
    /**
     * THE AVERAGE ROOM, so a graded house earns the same on average as a flat
     * one did. Individual rooms then charge above or below the rate the player
     * set, which is the entire point - but the BALANCE does not silently move
     * just because rooms stopped being identical. Without this, giving every
     * property a real floorplan would quietly re-tune the whole economy.
     */
    houseAverage: houseAverageMultiplier(house),
    rooms: Array.from({ length: roomCount }, (_, id) => {
      /**
       * WHO IS ALREADY IN THE HOUSE THIS MORNING.
       *
       * With a book, this is not a dice roll: it is whoever checked in on an
       * earlier day and has nights left. That is the whole meaning of "the next
       * day starts where the last one ended" - a guest three nights into a
       * five-night stay is upstairs because they are upstairs, not because a
       * random number said so.
       */
      const entityId = house ? house[id].id : null;
      const resident = residents ? residents.find((b) => b.roomId === entityId) : null;
      const occupied = residents ? Boolean(resident)
        : random() < (config.startOccupancy ?? 0.55);
      // The persistent Room entity, when the property has one. Everything the
      // day needs of it is copied onto the flat day-room below so the rest of
      // the simulation is untouched; `entity` is how the new systems - grade
      // pricing, allocation, the rooms screen - reach the real object.
      const entity = house ? house[id] : null;
      return {
        id: entity ? entity.id : id,
        entity,
        beds: entity ? entity.spec.beds : STANDARD_BEDS,
        capacity: entity ? entity.capacity : STANDARD_BEDS,
        // A refurbished room is a room that does not draw a complaint. Without a
        // floorplan there is nothing to distinguish them, so the first N are.
        upgraded: entity ? entity.condition !== "standard" && entity.condition !== "tired"
          : id < upgradedRooms,
        extraBed: entity ? entity.extraBeds > 0 : false,
        state: occupied ? ROOM.OCCUPIED : ROOM.CLEAN,
        guestId: null,
        nightsLeft: resident
          ? Math.max(0, resident.departureDay - (options.today ?? resident.arrivalDay))
          : (occupied ? 1 + Math.floor(random() * 3) : 0),
        inHouse: occupied,
        // Only the guests whose LAST night was last night check out this
        // morning. Everyone else stays put, and their room never comes free.
        /**
         * CHECK-OUT IS UNTIL 12:00, so departures land in the morning that runs
         * up to it - not scattered across the raw day. On a real 24-hour clock
         * the old `4 + random() * 35% of the day` put guests at the desk
         * settling their bill at half past midnight.
         */
        checkoutAt: occupied
          && (!resident || resident.departureDay <= (options.today ?? 0))
          ? checkoutTime(today, config.durationSec, random) : null,
      };
    }),
    reservations,
    nextPhoneAt: config.phoneCalls > 0 ? 8 * stretch : Infinity,
    phoneCallsLeft: config.phoneCalls,
    guests: [],
    tasks: [],
    staff,
    player: { taskId: null, busyUntil: 0 },
    /** The fullest the house has been today - what F&B trades against. */
    peakInHouse: 0,
    money: 0, tips: 0,
    /**
     * The till and the card machine, tracked separately as the day runs so the
     * player watches BOTH climb rather than waiting for a settlement that used
     * to arrive only at midnight.
     */
    cash: 0, card: 0,
    /** What the day's work consumed in stock. The other half of the cost base. */
    supplies: 0,
    supplyByKind: { linen: 0, amenities: 0, desk: 0, parts: 0 },
    linenTurns: 0,
    satisfaction: 70,
    checkedIn: 0, walkedOut: 0, missed: 0,
    overbooked: 0, walkIns: 0, bookingsTaken: 0, bookingsDeclined: 0,
    tipsGiven: 0, escortsDone: 0, tookOver: 0, nightsSold: 0, checkouts: 0,
    /** Favours asked by guests already upstairs. See GUEST_REQUEST_RATE. */
    requests: 0, requestsDone: 0,
    /**
     * EXPERIENCE EARNED ON THE FLOOR SO FAR TODAY, and the jobs behind it.
     * `game.js` pushes both into the property as they happen - see syncCareer.
     */
    experience: 0,
    career: {},
    /** Night-shift jobs done tonight, and the ones done LAST night. See NIGHT_PREP. */
    prepDone: 0,
    preppedFor: Math.max(0, Math.round(options.preppedFor ?? 0)),
    /** How much of last night's preparation today has already spent. */
    prepUsed: 0,
    /** In-game hours guests spent waiting past the 14:00 grace. See WAIT_LADDER. */
    hoursKeptWaiting: 0,
    /** Guests who gave up and went to another hotel, at our expense. */
    relocatedByWait: 0,
    /**
     * Free rooms per night, `[0]` being tonight. The day's running view of the
     * forward book - a whole Calendar cloned on every tick would be far too
     * expensive on a phone, and this answers the only question the desk asks.
     */
    forwardFree: Array.isArray(options.forwardFree) ? [...options.forwardFree] : null,
    /** Forward bookings taken on the phone today, for write-back at settle. */
    enquiriesTaken: [],
    /** Calls refused because a trained desk kept the last room back. */
    roomsHeldBack: 0,
    /** Upgrades sold at the desk, and what they were worth. */
    upsells: 0, upsellRevenue: 0,
    /** Upgrades handed over instead. Costs the premium, buys the review. */
    upgradesGiven: 0, upsellsDeclined: 0,
  };
}

function nextRandom(shift) {
  const value = mulberry32(shift.rngState)();
  shift.rngState = Math.floor(value * 4294967296);
  return value;
}

function clone(shift) {
  return {
    ...shift,
    // Both are MUTATED as the day runs, so they have to be copied or a replay
    // would inherit the previous tick's decisions.
    forwardFree: shift.forwardFree ? [...shift.forwardFree] : null,
    enquiriesTaken: shift.enquiriesTaken.map((e) => ({ ...e })),
    rooms: shift.rooms.map((r) => ({ ...r })),
    reservations: shift.reservations.map((r) => ({ ...r })),
    guests: shift.guests.map((g) => ({ ...g })),
    tasks: shift.tasks.map((t) => ({ ...t })),
    staff: shift.staff.map((s) => ({ ...s })),
    player: { ...shift.player },
  };
}

function addTask(shift, type, {
  guestId = null, roomId = null, expiresIn = null, addBed = null, flavour = null,
}) {
  const task = {
    id: shift.nextId++, type, guestId, roomId,
    addBed,
    /** What a REQUEST is actually for. See REQUEST_FLAVOURS. Null on every other task. */
    flavour,
    createdAt: shift.time,
    expiresAt: expiresIn === null ? null : shift.time + expiresIn,
    claimedBy: null, doneAt: null, expired: false,
  };
  shift.tasks.push(task);
  return task;
}

/**
 * A guest at the desk waiting for a room. See WAIT_LADDER.
 *
 * The deadline is measured from when the hotel's PROMISE starts, not from when
 * the guest walked in, so an early arrival costs nothing until 14:00. On a day
 * that does not teach the ladder yet (day 1) this is the old flat patience.
 */
function addCheckIn(shift, guest) {
  if (!teachesWaiting(shift)) {
    return addTask(shift, TASK.CHECK_IN, {
      guestId: guest.id, expiresIn: shift.config.patienceSec,
    });
  }
  const hour = hourSeconds(shift);
  const from = patienceStartsAt(shift, shift.time);
  const { min, max } = WAIT_LADDER.leaveAfterHours;
  const leaveAfter = min + nextRandom(shift) * (max - min);
  const task = addTask(shift, TASK.CHECK_IN, { guestId: guest.id, expiresIn: null });
  /** When the hotel starts owing this guest a room. */
  task.dueFrom = from;
  /** They give up here - relocation, not a shrug. */
  task.expiresAt = from + leaveAfter * hour;
  return task;
}

export function taskSeconds(type, worker) {
  return TASK_SECONDS[type] * (worker && worker !== "player" ? worker.speed : 1);
}

/**
 * What a check-in costs TODAY, after last night's preparation.
 *
 * The whole return on the night shift, and it is deliberately felt rather than
 * announced: the keys are cut and the paperwork is on the counter, so the desk
 * moves faster in the morning. Each prep covers one check-in, then it is used
 * up - you cannot prepare once and coast for a week.
 *
 * Never below a third of the normal time. A check-in still involves a person.
 */
export function checkInSeconds(shift, worker) {
  const base = taskSeconds(TASK.CHECK_IN, worker);
  if ((shift.preppedFor ?? 0) - (shift.prepUsed ?? 0) <= 0) return base;
  return Math.max(base / 3, base - NIGHT_PREP.savesPerCheckIn);
}

export function firstCleanRoom(shift) {
  return shift.rooms.find((r) => r.state === ROOM.CLEAN) || null;
}

/**
 * A clean room that can actually sleep this party. A party of three needs the
 * extra bed already wheeled in - selling them a two-bed room is not a room.
 */
export function roomFor(shift, guests = 2) {
  // Levels that do not yet model extra beds must not become unwinnable because a
  // family of three arrived: without the BED task there is no way to make a room
  // fit them, so those levels simply accommodate any party.
  const modelsBeds = shift.config.tasks.includes(TASK.BED);
  const clean = shift.rooms.filter((r) => r.state === ROOM.CLEAN);
  if (!modelsBeds) return clean[0] || null;

  // WITH A REAL FLOORPLAN, capacity is the room's own. A family room sleeps four
  // without anybody wheeling a bed in, and a single sleeps one however many beds
  // you try to add - which is the whole reason room TYPE is worth modelling.
  //
  // Tightest fit first: put the couple in the double and keep the family room
  // for a family. Front office does this by reflex and the day should too.
  const fits = clean.filter((r) => (r.entity ? r.capacity >= guests
    : guests <= STANDARD_BEDS || r.extraBed));
  if (fits.length === 0) return null;
  return fits.reduce((best, r) => (r.capacity < best.capacity ? r : best), fits[0]);
}

export function roomsAvailable(shift) {
  return shift.rooms.filter((r) => r.state === ROOM.CLEAN).length;
}

/**
 * The grade of room this guest actually paid for.
 *
 * Guests book a TYPE, not a door - "a double", "a family room" - and get
 * whatever the desk allocates. So the baseline an allocation is judged against
 * is a standard, no-view version of the type they booked. A sea-view double is
 * then an upgrade on a booked double, which is exactly right and needs no
 * separate table.
 */
export function bookedMultiplier(shift, guest) {
  const type = guest && guest.bookedType ? guest.bookedType : null;
  const spec = type && ROOM_TYPE_RATE[type] ? ROOM_TYPE_RATE[type] : null;
  if (!spec) return shift.houseAverage || 1;
  return spec;
}

/**
 * Type rates, mirrored from domain/Room.js.
 *
 * Duplicated rather than imported ON PURPOSE: engine.js is imported BY
 * domain/Floorplan.js (for the seeded RNG), so importing Room.js back would
 * close a cycle. The test `room type rates agree across the two modules` holds
 * them together, which is the same trick FACILITY_TRADE used before it.
 */
export const ROOM_TYPE_RATE = {
  single: 0.75, double: 1.0, twin: 1.0, family: 1.35, junior_suite: 1.7, suite: 2.4,
};

/**
 * Which room this guest gets, and what that decision cost or earned.
 *
 * Returns the whole outcome rather than just a room, because the check-in has
 * to bank an upsell, credit goodwill, or do neither - and the results card has
 * to be able to say which happened and how often.
 */
export function chooseRoom(shift, guest) {
  const guests = guest ? guest.guests : 2;
  const available = shift.rooms.filter((r) => r.state === ROOM.CLEAN
    && (r.entity ? r.capacity >= guests : true));
  if (available.length === 0) return null;

  const grade = (room) => (room.entity ? room.entity.rateMultiplier : 1);
  const booked = bookedMultiplier(shift, guest);
  const policy = shift.upsellPolicy || UPSELL_POLICY.PROTECT;

  // Rooms that honour what they paid for.
  //
  // TYPE is the promise; VIEW IS NOT. A guest who booked a double is owed a
  // double - any double, including the interior one over the bins. Comparing
  // the full grade here instead was a real bug: an interior double grades below
  // a plain double, so nobody who booked a double could ever be put in one, the
  // whole cheap end of the house became unsellable, and a graded property
  // started out-earning a flat one - which is backwards, and hid the very gap
  // that upselling exists to close.
  //
  // If nothing honours the booking the whole list is the list, because a
  // downgrade beats turning them away at the door.
  const typeRate = (room) => (room.entity ? (ROOM_TYPE_RATE[room.entity.type] ?? 1) : 1);
  const honours = available.filter((r) => typeRate(r) >= booked - 0.005);
  const pool = honours.length ? honours : available;
  const tightest = pool.reduce((best, r) => (grade(r) < grade(best) ? r : best), pool[0]);

  if (policy === UPSELL_POLICY.PROTECT || !tightest.entity) {
    return { room: tightest, mode: "as_booked", upsell: 0, satisfaction: 0 };
  }

  // Is there something genuinely better sitting empty? A 5% step is the
  // threshold below which nobody would notice and nobody would pay.
  const better = available.filter((r) => grade(r) > grade(tightest) + 0.05);
  if (better.length === 0) {
    return { room: tightest, mode: "as_booked", upsell: 0, satisfaction: 0 };
  }
  const best = better.reduce((top, r) => (grade(r) > grade(top) ? r : top), better[0]);
  const step = grade(best) - grade(tightest);
  const nights = guest && guest.nights ? guest.nights : 1;

  if (policy === UPSELL_POLICY.DELIGHT) {
    return {
      room: best,
      mode: "given",
      upsell: 0,
      satisfaction: Math.round((step / 0.1) * UPGRADE_DELIGHT),
    };
  }

  // SELL. Price the difference for the whole stay, discounted because it is an
  // impulse against a room that was going to sit empty anyway.
  const perNight = shift.roomRate * (step / Math.max(0.01, shift.houseAverage || 1));
  const price = Math.max(1, Math.round(perNight * nights * UPSELL_CAPTURE_RATE));
  const bookedTotal = Math.max(1, shift.roomRate * nights);
  if (nextRandom(shift) < upsellAcceptance(price, bookedTotal)) {
    return { room: best, mode: "sold", upsell: price, satisfaction: 0 };
  }
  return { room: tightest, mode: "declined", upsell: 0, satisfaction: 0 };
}

/** An upgrade sold at the desk goes for this share of its rack difference. */
export const UPSELL_CAPTURE_RATE = 0.55;

/** Beds sold but not yet occupied - the number that decides overbooking. */
export function outstandingBookings(shift) {
  return shift.reservations.filter((r) => !r.arrived).length;
}

export function canStart(shift, taskId) {
  if (shift.player.taskId !== null) return false;
  const task = shift.tasks.find((t) => t.id === taskId);
  if (!task || task.doneAt !== null || task.claimedBy !== null) return false;
  if (task.type === TASK.CHECK_IN) {
    const guest = shift.guests.find((g) => g.id === task.guestId);
    if (!roomFor(shift, guest ? guest.guests : 2)) return false;
  }
  return true;
}

export function startTask(shift, taskId) {
  if (!canStart(shift, taskId)) throw new Error(`Cannot start task ${taskId}`);
  const next = clone(shift);
  const task = next.tasks.find((t) => t.id === taskId);
  task.claimedBy = "player";
  next.player.taskId = taskId;
  next.player.busyUntil = next.time + workSeconds(next, task, "player");
  return next;
}

/** Seconds this task will take this worker, with last night's prep applied. */
export function workSeconds(shift, task, worker) {
  if (task.type !== TASK.CHECK_IN) return taskSeconds(task.type, worker);
  const seconds = checkInSeconds(shift, worker);
  if (seconds < taskSeconds(TASK.CHECK_IN, worker)) {
    shift.prepUsed = (shift.prepUsed ?? 0) + 1;
    task.prepped = true;
  }
  return seconds;
}

/**
 * `worker` is the string "player" or the staff member who did the job. Who did
 * it matters: a reservations desk exercises judgement on the phone that nobody
 * else in the building has.
 */
/**
 * TAKE MONEY. Every payment goes through here so the cash/card split can never
 * be skipped at a call site - four places add to the till and each one would
 * otherwise have to remember.
 */
function takePayment(shift, amount, options = {}) {
  const split = splitPayment(amount, shift.stars, options);
  shift.money += split.cash + split.card;
  shift.cash += split.cash;
  shift.card += split.card;
  return split;
}

/**
 * Hand a departed guest's room to housekeeping.
 *
 * Called when the CHECK_OUT task completes - or immediately, on a level that
 * does not model check-out yet, so no configuration can strand a room.
 */
function releaseRoom(shift, room) {
  room.awaitingCheckout = false;
  const breaks = shift.config.breakChance > 0 && nextRandom(shift) < shift.config.breakChance;
  if (breaks && shift.config.tasks.includes(TASK.REPAIR)) {
    room.state = ROOM.BROKEN;
    room.wasBroken = true;
    addTask(shift, TASK.REPAIR, { roomId: room.id, expiresIn: null });
  } else if (shift.config.tasks.includes(TASK.CLEAN)) {
    room.state = ROOM.DIRTY;
    room.wasDirty = true;
    addTask(shift, TASK.CLEAN, { roomId: room.id, expiresIn: null });
  } else {
    room.state = ROOM.CLEAN;
  }
}

function completeTask(shift, task, worker) {
  task.doneAt = shift.time;

  /**
   * PAID THE MOMENT IT IS DONE, and only for work the PLAYER did. Staff doing
   * their own job is the hotel running, not the owner learning it - and paying
   * the owner for it is exactly what `dayExperience` stopped doing when the desk
   * is staffed. The two rules have to agree or hiring becomes a way to farm.
   */
  if (worker === "player") {
    shift.experience += TASK_XP[task.type] ?? 0;
    const counter = CAREER_COUNTER[task.type];
    if (counter) shift.career[counter] = (shift.career[counter] ?? 0) + 1;
  }

  // Stock is consumed by the WORK, not by the guest, so it is charged here -
  // a room turned for nobody still costs a set of linen.
  const spent = taskSupplyCost(shift, task);
  if (spent > 0) {
    shift.supplies += spent;
    for (const kind of TASK_SUPPLIES[task.type] || []) {
      shift.supplyByKind[kind] = (shift.supplyByKind[kind] || 0)
        + supplyCost(kind, { stars: shift.stars, facilities: shift.facilities });
    }
    // Counted so the results card can price the laundry decision honestly.
    if ((TASK_SUPPLIES[task.type] || []).includes(SUPPLY.LINEN)) shift.linenTurns += 1;
  }

  const reward = TASK_REWARD[task.type];
  shift.money += reward.money;
  shift.satisfaction = Math.min(100, shift.satisfaction + reward.satisfaction);

  if (task.type === TASK.ESCORT) {
    const guest = shift.guests.find((g) => g.id === task.guestId);
    if (guest) guest.escorted = true;
    if (shift.config.escortCarriesBags) {
      shift.satisfaction = Math.min(100, shift.satisfaction + 3);
    }
    // A tip is a gift, not a fee. Most guests do not leave one; guests paying a
    // premium rate tip more often and more generously, which is why the room
    // rate you set quietly decides how much of your income is tips.
    const generosity = shift.roomRate / Math.max(1, shift.fairRate);
    const chance = clamp(0.10 + 0.10 * shift.stars + 0.30 * (generosity - 0.85), 0.05, 0.85);
    if (nextRandom(shift) < chance) {
      const bagsUp = shift.config.escortCarriesBags ? 1.6 : 1;
      const size = 0.03 + nextRandom(shift) * 0.07;   // 3-10% of the room rate
      const tip = Math.max(1, Math.round(shift.roomRate * size * bagsUp));
      // Tips are cash. Always, everywhere.
      shift.money += tip;
      shift.cash += tip;
      shift.tips += tip;
      shift.tipsGiven += 1;
    }
    shift.escortsDone += 1;
  }

  if (task.type === TASK.BED) {
    const room = shift.rooms.find((r) => r.id === task.roomId);
    if (room) room.extraBed = task.addBed === true;
  }

  if (task.type === TASK.CHECK_IN) {
    const guest = shift.guests.find((g) => g.id === task.guestId);
    // ALLOCATION, not just "the next clean room". Which door this guest gets is
    // a decision worth money in both directions - see chooseRoom.
    const choice = guest ? chooseRoom(shift, guest) : null;
    const room = choice ? choice.room : firstCleanRoom(shift);
    if (room && guest) {
      if (choice && choice.mode === "sold") {
        takePayment(shift, choice.upsell);
        shift.upsellRevenue += choice.upsell;
        shift.upsells += 1;
      } else if (choice && choice.mode === "given") {
        shift.satisfaction = Math.min(100, shift.satisfaction + choice.satisfaction);
        shift.upgradesGiven += 1;
      } else if (choice && choice.mode === "declined") {
        shift.upsellsDeclined += 1;
      }
      room.state = ROOM.OCCUPIED;
      room.guestId = guest.id;
      room.nightsLeft = guest.nights;
      room.inHouse = true;
      guest.roomId = room.id;
      guest.checkedInAt = shift.time;

      // The whole stay is charged on arrival: nights x rate, plus a supplement
      // for a third or fourth body in a two-bed room.
      const beds = room.entity ? room.entity.spec.capacity : STANDARD_BEDS;
      const extraGuests = Math.max(0, guest.guests - beds);
      // The rate the player set is the rate of an AVERAGE room. This one charges
      // what it is actually worth - which is how a sea view earns its premium
      // without the player having to price every door individually.
      const grade = roomGradeFactor(shift, room);
      const nightly = shift.roomRate * grade * (1 + extraGuests * EXTRA_GUEST_RATE);
      takePayment(shift, Math.round(nightly * guest.nights));
      guest.gradeFactor = grade;
      guest.roomNumber = room.entity ? room.entity.number : null;
      shift.nightsSold += guest.nights;
      // What they will judge you on later.
      guest.waitedAtDesk = shift.time - guest.arrivedAt;
      guest.escorted = false;
      // How the room reached them - a turned-around room that was recently
      // broken or dirty is remembered in the review.
      guest.roomWasBroken = Boolean(room.wasBroken);
      guest.roomWasDirty = Boolean(room.wasDirty);
      guest.roomUpgraded = Boolean(room.upgraded);
      guest.roomModifier = room.entity ? room.entity.reviewModifier : null;
      room.wasBroken = false;
      room.wasDirty = false;
      shift.checkedIn += 1;
      guest.allocation = choice ? choice.mode : "as_booked";
      if (shift.config.tasks.includes(TASK.ESCORT)) {
        addTask(shift, TASK.ESCORT, { guestId: guest.id, roomId: room.id, expiresIn: 13 });
      }
    }
  }

  if (task.type === TASK.PHONE) {
    /**
     * SOMEBODY WANTS A ROOM. The question is whether taking it is a sale or a
     * problem you have not met yet.
     *
     * With a forward book this is a real decision rather than a coin flip: the
     * enquiry is for a stay some days out, and whether it can be honoured
     * depends on every night of it. Who is on the phone decides which of those
     * questions actually gets asked - see DESK_TIER.
     *
     * A reservations person is trained for this. Reception is not, and answers
     * as a trainee would. The PLAYER always takes the call, because they can
     * see the book themselves and the consequence is theirs.
     */
    const enquiry = task.enquiry ?? makeEnquiry(shift);
    const onDesk = worker && worker !== "player";
    const tier = !onDesk ? null
      : worker.role === ROLE.RESERVATIONS ? worker.tier : 1;

    const verdict = tier === null ? { accept: true, reason: "player" }
      : judgeEnquiry(shift, enquiry, tier);

    if (!verdict.accept) {
      shift.bookingsDeclined += 1;
      if (verdict.reason === "held_back") shift.roomsHeldBack += 1;
      return;
    }

    shift.bookingsTaken += 1;
    // Hold the nights on the day's running ledger, so a second call cannot sell
    // the same room over again.
    for (let n = 0; n < enquiry.nights; n += 1) {
      const at = enquiry.inDays + n;
      if (shift.forwardFree && shift.forwardFree[at] !== undefined) {
        shift.forwardFree[at] = Math.max(0, shift.forwardFree[at] - 1);
      }
    }
    // Written back to the property's book when the day settles.
    shift.enquiriesTaken.push({ ...enquiry });

    // An enquiry for TODAY still turns up today - that is a walk-up booking and
    // it is the one that can still overbook you if you took it carelessly.
    if (enquiry.inDays === 0) {
      shift.reservations.push({
        id: shift.nextId++,
        dueAt: shift.time + 22 + nextRandom(shift) * 16,
        source: "phone",
        nights: enquiry.nights,
        guests: enquiry.guests,
        bookingId: null,
        arrived: false, housed: null,
      });
    }
  }

  if (task.type === TASK.CHECK_OUT) {
    const room = shift.rooms.find((r) => r.id === task.roomId);
    if (room) releaseRoom(shift, room);
  }

  if (task.type === TASK.CLEAN || task.type === TASK.REPAIR) {
    const room = shift.rooms.find((r) => r.id === task.roomId);
    if (room) { room.state = ROOM.CLEAN; room.guestId = null; }
  }

  if (task.type === TASK.REQUEST) shift.requestsDone += 1;

  // The night's work is stored, not spent. It comes back as faster check-ins.
  if (task.type === TASK.PREP) shift.prepDone += 1;
}

/**
 * The review a departing guest leaves, scored 1-5 per category.
 *
 * Everything is judged AGAINST WHAT THEY PAID. The same slow check-in is a
 * shrug at a bargain rate and a one-star complaint at a premium one, which is
 * why underpricing is a real strategy and overpricing punishes sloppiness twice.
 */
export function reviewGuest(shift, guest) {
  const expectation = shift.expectation;
  const tolerance = 1 - expectation;          // 0 = unforgiving, 1 = easy-going
  const score = {};

  // Welcome: how long they stood at the desk.
  const waited = guest.waitedAtDesk ?? 0;
  const allowed = 4 + tolerance * 12;
  score.welcome = clamp(5 - (waited - allowed) / 4, 1, 5);

  // Room: what state it was in when they got it. A refurbishment is worth
  // nothing to a bargain hunter - a clean room already scores full marks for
  // them - and everything to a guest paying a premium, who notices the tired
  // carpet a forgiving guest would not mention. That is why refurbishing pays
  // for itself only once you are charging properly for the place.
  score.room = guest.roomWasBroken ? 2 : guest.roomWasDirty ? 2.5 : 5;
  // A real room is judged on what it actually is - a tired interior single reads
  // differently from a refurbished room with a view, and `reviewModifier`
  // carries both. Falls back to the flat upgraded flag when there is no
  // floorplan behind the guest.
  const roomQuality = guest.roomModifier ?? (guest.roomUpgraded ? 0.6 : 0);
  score.room = clamp(score.room + (tolerance - 0.5) + roomQuality, 1, 5);

  // Service: did anyone take them up.
  score.service = guest.escorted ? 5 : clamp(2.5 + tolerance * 2, 1, 5);

  // Value: the rate against what a property of this class and standing may ask.
  const ratio = shift.roomRate / Math.max(1, shift.fairRate);
  score.value = clamp(5 - (ratio - 0.9) * 4.5, 1, 5);

  const overall = REVIEW_CATEGORIES.reduce((sum, key) => sum + score[key], 0)
    / REVIEW_CATEGORIES.length;
  return { guestId: guest.id, categories: score, overall: Math.round(overall * 10) / 10 };
}

/** Roles the player is NOT covering with staff - used by the UI and the hint. */
export function staffedTaskTypes(shift) {
  const covered = new Set();
  for (const person of shift.staff) {
    for (const type of ROLE_TASKS[person.role]) covered.add(type);
  }
  return covered;
}

export function tick(shift, dt) {
  if (shift.over) return shift;
  const next = clone(shift);
  next.time += dt;

  // --- the player finishes
  if (next.player.taskId !== null && next.time >= next.player.busyUntil) {
    const task = next.tasks.find((t) => t.id === next.player.taskId);
    if (task) completeTask(next, task, "player");
    next.player.taskId = null;
  }

  // --- staff: finish, recover, then pick up
  for (const person of next.staff) {
    if (person.taskId !== null) {
      if (next.time >= person.busyUntil) {
        const task = next.tasks.find((t) => t.id === person.taskId);
        if (task) completeTask(next, task, person);
        person.taskId = null;
        person.busyUntil = null;
      } else {
        continue;
      }
    }
    // Idle staff recover. This is the only way energy comes back.
    person.energy = Math.min(person.maxEnergy, person.energy + ENERGY_REGEN * dt);
    if (person.energy >= person.maxEnergy * 0.5) person.restedOut = false;
    if (person.restedOut || person.energy < ENERGY_FLOOR) { person.restedOut = true; continue; }

    // A role the PLAYER has taken over is no longer covered by staff. Without
    // this, level 5's receptionist keeps answering the phone, the reservations
    // desk has nothing to do, and the shift passes itself untouched.
    const excluded = next.config.staffExcludes || [];
    const types = ROLE_TASKS[person.role].filter((t) => !excluded.includes(t));
    const waiting = next.tasks.find(
      (t) => types.includes(t.type) && t.doneAt === null && t.claimedBy === null
        && (t.type !== TASK.CHECK_IN || firstCleanRoom(next)),
    );
    if (waiting) {
      waiting.claimedBy = person.id;
      person.taskId = waiting.id;
      person.busyUntil = next.time + workSeconds(next, waiting, person);
      person.energy = Math.max(0, person.energy - TASK_ENERGY[waiting.type]);
    }
  }

  /**
   * --- KEPT WAITING PAST THE GUARANTEE. See WAIT_LADDER.
   *
   * Satisfaction bleeds by the in-game HOUR, not per tick, so the cost is the
   * same whether the day is 120 seconds or ten minutes long - it is measured in
   * the hotel's time, which is the only time the guest experiences.
   */
  if (teachesWaiting(next)) {
    const hour = hourSeconds(next);
    for (const task of next.tasks) {
      if (task.type !== TASK.CHECK_IN || task.doneAt !== null) continue;
      if (task.dueFrom === undefined || next.time < task.dueFrom) continue;
      const lateHours = (next.time - task.dueFrom) / hour;
      if (lateHours < WAIT_LADDER.graceHours) continue;
      // COUNTED FROM THE END OF THE GRACE, so the first hit lands exactly on
      // "1 hour delay" as the operator described it, and every further whole
      // hour costs again. Counting whole hours of the CLOCK instead would put
      // the first one at two hours late and quietly halve the rule.
      const due = Math.floor(lateHours - WAIT_LADDER.graceHours) + 1;
      const owed = due - (task.hoursCharged ?? 0);
      if (owed <= 0) continue;
      task.hoursCharged = due;
      next.satisfaction = Math.max(0,
        next.satisfaction - owed * WAIT_LADDER.satisfactionPerHour);
      next.hoursKeptWaiting = (next.hoursKeptWaiting ?? 0) + owed;
    }
  }

  // --- deadlines
  for (const task of next.tasks) {
    if (task.doneAt !== null || task.claimedBy !== null) continue;
    if (task.expiresAt !== null && next.time >= task.expiresAt) {
      task.doneAt = next.time;
      task.expired = true;
      next.missed += 1;
      /**
       * A GUEST WHO GAVE UP ON A ROOM GOES TO ANOTHER HOTEL, AND WE PAY FOR IT.
       *
       * The operator: "if its 2-3 hours they can choose to change the hotel and
       * loose moned for relocation and loose more satisfaction." A relocation is
       * not a shrug - it is the desk phoning round, the taxi, and the rate
       * difference, which is why it already has a price in OVERBOOK_PENALTY.
       * Being slow now costs what overselling costs, because to the guest
       * standing there it is the same failure.
       */
      if (task.type === TASK.CHECK_IN && teachesWaiting(next)) {
        next.walkedOut += 1;
        next.relocatedByWait = (next.relocatedByWait ?? 0) + 1;
        next.money -= OVERBOOK_PENALTY.money;
        next.satisfaction = Math.max(0,
          next.satisfaction - OVERBOOK_PENALTY.satisfaction);
        const waiting = next.guests.find((g) => g.id === task.guestId);
        if (waiting) waiting.state = "relocated";
        continue;
      }
      next.satisfaction = Math.max(0, next.satisfaction - (EXPIRY_PENALTY[task.type] ?? 4));
      if (task.type === TASK.CHECK_IN) next.walkedOut += 1;
      // A guest who gave up waiting to check out still LEFT. Release the room,
      // or an unattended desk quietly bricks the hotel one room at a time.
      if (task.type === TASK.CHECK_OUT) {
        const room = next.rooms.find((r) => r.id === task.roomId);
        if (room) releaseRoom(next, room);
      }
    }
  }

  // --- morning checkouts: the in-house guests whose stay ended overnight.
  // A room turns AT MOST once a day, which is what a real house does.
  for (const room of next.rooms) {
    if (room.state !== ROOM.OCCUPIED || !room.inHouse) continue;
    if (room.checkoutAt === null || next.time < room.checkoutAt) continue;
    /**
     * A DEPARTURE IS WORK. The operator: "we still dont have check out work for
     * the reception but this is wrong."
     *
     * The room used to go straight to CLEAN with nothing for anyone to do,
     * which quietly removed half of what day 1 is meant to teach AND half of
     * the desk's events. Now the guest is at the desk with a folio to settle,
     * and the room is not released to housekeeping until they have gone.
     */
    room.inHouse = false;
    room.checkoutAt = null;
    room.awaitingCheckout = true;
    next.checkouts += 1;
    addTask(next, TASK.CHECK_OUT, {
      roomId: room.id, guestId: room.guestId, expiresIn: next.config.patienceSec * 1.6,
    });
    room.guestId = null;
    // A departing guest reviews the WHOLE stay, most of which happened on days
    // we do not simulate. Their experience is modelled from how the house is
    // being run right now - the honest proxy available in a one-day prototype.
    const standard = next.satisfaction / 100;
    next.reviews.push(reviewGuest(next, {
      id: `inhouse-${room.id}`,
      waitedAtDesk: 3 + (1 - standard) * 14,
      escorted: standard > 0.6,
      roomWasBroken: false,
      roomWasDirty: standard < 0.35,
      roomUpgraded: room.upgraded,
      roomModifier: room.entity ? room.entity.reviewModifier : null,
    }));
    // The room is NOT released here. It goes to housekeeping when the guest has
    // actually checked out - see releaseRoom, called from the CHECK_OUT task.
  }

  // --- an extra bed nobody has asked for is a bed in the way. If the room is
  // clean, carries a bed, and no arriving party needs one, wheel it back out.
  if (next.config.tasks.includes(TASK.BED)) {
    const needBed = next.reservations.some((r) => !r.arrived && r.guests > STANDARD_BEDS)
      || next.guests.some((g) => g.state === "waiting" && g.guests > STANDARD_BEDS);
    for (const room of next.rooms) {
      const pending = next.tasks.some((t) => t.type === TASK.BED && t.roomId === room.id
        && t.doneAt === null);
      if (pending || room.state !== ROOM.CLEAN) continue;
      if (room.extraBed && !needBed) {
        addTask(next, TASK.BED, { roomId: room.id, expiresIn: null, addBed: false });
      } else if (!room.extraBed && needBed
        && !next.rooms.some((r) => r.state === ROOM.CLEAN && r.extraBed)) {
        addTask(next, TASK.BED, { roomId: room.id, expiresIn: null, addBed: true });
      }
    }
  }

  // --- legacy same-day turnover (levels that do not model overnight stays)
  for (const room of next.rooms) {
    if (room.state !== ROOM.OCCUPIED || room.inHouse) continue;
    const guest = next.guests.find((g) => g.id === room.guestId);
    if (!guest || guest.checkedInAt === undefined) continue;
    if (next.time - guest.checkedInAt >= next.config.staySec) {
      guest.state = "checked_out";
      next.reviews.push(reviewGuest(next, guest));   // they leave a review on the way out
      const breaks = next.config.breakChance > 0 && nextRandom(next) < next.config.breakChance;
      if (breaks && next.config.tasks.includes(TASK.REPAIR)) {
        room.state = ROOM.BROKEN;
        room.wasBroken = true;
        addTask(next, TASK.REPAIR, { roomId: room.id, expiresIn: null });
      } else if (next.config.tasks.includes(TASK.CLEAN)) {
        room.state = ROOM.DIRTY;
        room.wasDirty = true;
        addTask(next, TASK.CLEAN, { roomId: room.id, expiresIn: null });
      } else {
        room.state = ROOM.CLEAN;
        room.guestId = null;
      }
    }
  }

  // --- the book: reserved guests turn up whether or not you are ready
  for (const reservation of next.reservations) {
    if (reservation.arrived || next.time < reservation.dueAt) continue;
    reservation.arrived = true;
    const anyRoomComing = next.rooms.some((r) => r.state !== ROOM.OCCUPIED);
    if (!anyRoomComing) {
      // Sold a bed that does not exist. This is what overbooking actually costs.
      reservation.housed = false;
      next.overbooked += 1;
      next.money -= OVERBOOK_PENALTY.money;
      next.satisfaction = Math.max(0, next.satisfaction - OVERBOOK_PENALTY.satisfaction);
      continue;
    }
    const guest = {
      id: next.nextId++, state: "waiting", roomId: null, arrivedAt: next.time,
      nights: reservation.nights ?? 1, guests: reservation.guests ?? 2,
    };
    next.guests.push(guest);
    addCheckIn(next, guest);
  }

  /**
   * --- THE NIGHT SHIFT. See NIGHT_PREP. Only while it IS night, only on a day
   * that has a night to work (the onboarding days that teach reception), and
   * only ever a handful - the point is that the small hours are quiet, not that
   * they are secretly the busiest part of the day.
   */
  if (next.config.tasks.includes(TASK.PREP)) {
    const day = shiftDay(next);
    const spawned = next.tasks.filter((t) => t.type === TASK.PREP).length;
    const wanted = nightPrepJobs(next);
    // Day 1 opens at 08:00, so it simply has no night to work - which falls out
    // of the timetable rather than needing a special case here.
    if (isNightShift(day, next.config.durationSec, next.time) && spawned < wanted) {
      const slot = (NIGHT_PREP_HOURS.to - NIGHT_PREP_HOURS.from) / wanted;
      const dueBy = NIGHT_PREP_HOURS.from + slot * spawned;
      if (hourAtShift(next) >= dueBy) {
        addTask(next, TASK.PREP, {
          // No expiry. Nobody is standing there; the work is simply available.
          expiresIn: null,
        });
      }
    }
  }

  /**
   * --- THE PEOPLE ALREADY UPSTAIRS WANT THINGS. See GUEST_REQUEST_RATE.
   *
   * A per-second probability, deliberately not a batch at the top of the day: a
   * batch would fix the dead-gap statistic and hand the player a wall instead,
   * which is the same mistake in the other direction.
   *
   * Requests stop being generated near the close so the day does not end with
   * work nobody can reach - the tail is meant to be a breath, not a failure.
   */
  const occupied = next.rooms.filter((r) => r.state === ROOM.OCCUPIED && r.inHouse);
  const flavours = requestFlavours(next);
  if (flavours.length && occupied.length
    && next.time < next.config.durationSec - TASK_SECONDS[TASK.REQUEST] * 2) {
    const perSecond = (GUEST_REQUEST_RATE * occupied.length) / next.config.durationSec;
    if (nextRandom(next) < perSecond * dt) {
      // Whoever is not already the subject of a job. A guest fielding a second
      // request while the first is still open reads as a bug, not as a busy
      // hotel, and it is the shape that makes a board impossible to clear.
      const free = occupied.filter((room) => !next.tasks.some(
        (t) => t.type === TASK.REQUEST && t.roomId === room.id && t.doneAt === null));
      if (free.length) {
        const room = free[Math.floor(nextRandom(next) * free.length)];
        const flavour = flavours[Math.floor(nextRandom(next) * flavours.length)];
        next.requests += 1;
        addTask(next, TASK.REQUEST, {
          roomId: room.id, guestId: room.guestId,
          // Longer than a check-in's patience: a guest already in the building
          // is not going to walk out over a slow towel. They get annoyed, which
          // is what EXPIRY_PENALTY is for.
          expiresIn: next.config.patienceSec * 2.2,
          flavour,
        });
      }
    }
  }

  /**
   * --- WALK-INS: unbooked, only worth taking if you genuinely have space, and
   * only during the hours a hotel actually receives strangers.
   *
   * THE BUG: booked arrivals were anchored to real hours and this was not, so it
   * fired as a flat probability across the whole day and produced check-ins at
   * six in the morning. The operator: "now i get many check-ins between 00:00
   * and 08:00 this is not okay." See WALK_IN_HOURS in Schedule.js.
   */
  if (next.time < next.config.durationSec
    && acceptsWalkIns(shiftDay(next), next.config.durationSec, next.time)
    && nextRandom(next) < next.config.walkInChance * dt * 0.25) {
    if (roomsAvailable(next) > outstandingBookings(next)) {
      // Walk-ins are the genuine one-nighters, and there are few of them.
      const guest = {
        id: next.nextId++, state: "waiting", roomId: null, arrivedAt: next.time,
        walkIn: true, nights: 1, guests: pickWeighted(next, PARTY_MIX).guests,
      };
      next.guests.push(guest);
      next.walkIns += 1;
      addCheckIn(next, guest);
    }
  }

  // --- the phone
  if (next.phoneCallsLeft > 0 && next.time >= next.nextPhoneAt
      && next.time < next.config.durationSec - 25) {
    addTask(next, TASK.PHONE, { expiresIn: 14 });
    next.phoneCallsLeft -= 1;
    // Spread across the whole day rather than bunched into its first minutes.
    next.nextPhoneAt = next.time
      + (18 + nextRandom(next) * 14) * (next.config.dayStretch ?? 1);
  }

  // The house at its fullest is what the dining room serves - recorded as the
  // day runs, because by the final tick half of them have already left.
  next.peakInHouse = Math.max(next.peakInHouse || 0, guestsInHouse(next));

  if (next.time >= next.config.durationSec) next.over = true;
  return next;
}

export function openTasks(shift) {
  return shift.tasks
    .filter((t) => t.doneAt === null && t.claimedBy === null)
    .sort((a, b) => a.createdAt - b.createdAt);
}

/**
 * The floor, split into the three lists a person on shift actually thinks in.
 *
 *   mine    - nobody is on it and you can start it now
 *   staff   - someone is on it; you may still muck in and take it over
 *   blocked - it exists and NOBODY can do it yet (no clean room to give away)
 *
 * Keeping blocked work visible but separate matters: an operator needs to see
 * that a guest is stuck waiting because the house is full, not hunt for a job
 * that silently refuses to start.
 */
export function taskBoard(shift) {
  const mine = [];
  const blocked = [];
  for (const task of openTasks(shift)) {
    if (task.type === TASK.CHECK_IN && !firstCleanRoom(shift)) blocked.push(task);
    else mine.push(task);
  }
  const staff = shift.tasks
    .filter((t) => t.doneAt === null && t.claimedBy !== null && t.claimedBy !== "player")
    .sort((a, b) => a.id - b.id);
  return { mine, staff, blocked };
}

/** Can the player muck in and take a job off a struggling staff member? */
export function canTakeOver(shift, taskId) {
  if (shift.player.taskId !== null) return false;
  const task = shift.tasks.find((t) => t.id === taskId);
  if (!task || task.doneAt !== null) return false;
  if (task.claimedBy === null || task.claimedBy === "player") return false;
  if (task.type === TASK.CHECK_IN && !firstCleanRoom(shift)) return false;
  return true;
}

/**
 * Take a job off a staff member and do it yourself. The owner is faster, and
 * the work already done is lost - stepping in is help, not a free speed-up.
 */
export function takeOver(shift, taskId) {
  if (!canTakeOver(shift, taskId)) throw new Error(`Cannot take over task ${taskId}`);
  const next = clone(shift);
  const task = next.tasks.find((t) => t.id === taskId);
  const person = next.staff.find((s) => s.id === task.claimedBy);
  if (person) { person.taskId = null; person.busyUntil = null; }
  task.claimedBy = "player";
  next.player.taskId = taskId;
  next.player.busyUntil = next.time + taskSeconds(task.type, "player");
  next.tookOver += 1;
  return next;
}

export function taskUrgency(shift, task) {
  if (task.expiresAt === null) return 0;
  const total = task.expiresAt - task.createdAt;
  return Math.min(1, (shift.time - task.createdAt) / total);
}

export function suggestTask(shift) {
  const open = openTasks(shift).filter((t) => canStart(shift, t.id));
  if (open.length === 0) return null;
  return open.reduce((worst, t) =>
    taskUrgency(shift, t) > taskUrgency(shift, worst) ? t : worst, open[0]);
}

/**
 * Wages are charged for the whole shift, used or not.
 *
 * ROOMS-SIDE ONLY. The brigade's wages are charged inside the F&B P&L instead,
 * where they belong - an operator judges a restaurant on its own contribution
 * after its own labour, and counting a chef here as well would bill the player
 * twice for the same person. `fnbWages` is the other half; `score` reports both.
 */
export function dailyWages(shift) {
  return shift.staff.reduce((total, s) => total + (isFnbRole(s.role) ? 0 : s.wage), 0);
}

/**
 * What the laundry decision was worth today, in both directions.
 *
 * If the property has one, this is what was saved by not sending linen out. If
 * it does not, it is what a laundry WOULD have saved - the same number, shown
 * before you have paid for it, so the $1800 is a decision rather than a guess.
 */
export function laundrySwing(shift) {
  return Math.round(shift.linenTurns * (LINEN_COST.outsourced - LINEN_COST.inHouse));
}

export function score(shift) {
  const wages = dailyWages(shift);
  const supplies = Math.round(shift.supplies);
  // The facilities trade against whoever is in the house right now, so this is
  // live: as the hotel fills, the restaurant and bar earn and the takings the
  // rooms have to find come down.
  const trade = facilityTrade(shift);
  const profit = shift.money + trade.net - wages - supplies;
  // A dining room that turned people away, or one you built and never staffed,
  // is felt by the guests upstairs. This is the only place F&B touches the
  // satisfaction score, and it is bounded so it can never dominate the floor.
  const satisfaction = clamp(shift.satisfaction + trade.satisfaction, 0, 100);
  return {
    takings: Math.round(shift.money),
    cash: Math.round(shift.cash),
    card: Math.round(shift.card),
    wages,
    // Food and beverage, net of stock, of its own brigade, and of keeping the
    // place open. `facilityCosts` includes the brigade - see dailyWages.
    facilityRevenue: trade.revenue,
    facilityCosts: trade.cogs + trade.upkeep + trade.labour,
    facilityCogs: trade.cogs,
    facilityUpkeep: trade.upkeep,
    facilityLabour: trade.labour,
    facilityNet: trade.net,
    facilityBreakdown: trade.breakdown,
    coversTurnedAway: trade.turnedAway,
    fnbWages: fnbWages(shift),
    guestsInHouse: Math.round(guestsInHouse(shift)),
    /** The fullest the house got - the headcount the outlets actually served. */
    coversBase: Math.round(coversBase(shift)),
    // Bookings a reservations desk turned away rather than oversell the house.
    bookingsDeclined: shift.bookingsDeclined,
    /** Refusals that were a trained desk protecting the house, not a full hotel. */
    roomsHeldBack: shift.roomsHeldBack,
    /** Forward bookings the phone won today. */
    enquiriesTaken: shift.enquiriesTaken.length,
    // Stock consumed by the day's work: linen, amenities, key cards, parts.
    supplies,
    supplyByKind: Object.fromEntries(
      Object.entries(shift.supplyByKind).map(([kind, spent]) => [kind, Math.round(spent)]),
    ),
    hasLaundry: shift.facilities.includes(FACILITY.LAUNDRY),
    laundrySwing: laundrySwing(shift),
    profit: Math.round(profit),
    // What the till has to hold to clear the target once wages AND stock come
    // out. The UI tracks THIS during a day: showing profit from second zero
    // meant a day opened at minus the payroll, which reads as being punished for
    // having staff. It rises as stock is consumed, which is the lesson.
    needTakings: Math.max(0, Math.round(
      shift.config.targetProfit + wages + supplies - trade.net,
    )),
    tips: Math.round(shift.tips),
    target: shift.config.targetProfit,
    targetSatisfaction: shift.config.targetSatisfaction,
    satisfaction: Math.round(satisfaction),
    /** How much of that satisfaction the dining room moved, in either direction. */
    fnbSatisfaction: trade.satisfaction,
    checkedIn: shift.checkedIn,
    walkedOut: shift.walkedOut,
    missed: shift.missed,
    overbooked: shift.overbooked,
    /** See WAIT_LADDER - guests lost to a late room, and hours of lateness. */
    relocatedByWait: shift.relocatedByWait ?? 0,
    hoursKeptWaiting: shift.hoursKeptWaiting ?? 0,
    /** Experience earned by working, already banked live. See TASK_XP. */
    experience: shift.experience ?? 0,
    career: { ...(shift.career ?? {}) },
    /** Night-shift jobs done, which the property carries into tomorrow. */
    prepDone: shift.prepDone ?? 0,
    prepUsed: shift.prepUsed ?? 0,
    walkIns: shift.walkIns,
    bookingsTaken: shift.bookingsTaken,
    stars: shift.stars,
    certification: shift.certification,
    roomCount: shift.roomCount,
    nightsSold: shift.nightsSold,
    checkouts: shift.checkouts,
    roomRate: shift.roomRate,
    fairRate: shift.fairRate,
    tipsGiven: shift.tipsGiven,
    // What the desk did with the good rooms. Feeds the results card and the XP.
    upsells: shift.upsells,
    upsellRevenue: shift.upsellRevenue,
    upgradesGiven: shift.upgradesGiven,
    upsellsDeclined: shift.upsellsDeclined,
    escortsDone: shift.escortsDone,
    reviews: shift.reviews.length,
    // What guests actually said, 1-5. This is the number that should decide the
    // rate you can charge next time.
    rating: shift.reviews.length
      ? Math.round((shift.reviews.reduce((sum, r) => sum + r.overall, 0)
        / shift.reviews.length) * 10) / 10
      : null,
    categoryAverages: REVIEW_CATEGORIES.reduce((out, key) => {
      out[key] = shift.reviews.length
        ? Math.round((shift.reviews.reduce((sum, r) => sum + r.categories[key], 0)
          / shift.reviews.length) * 10) / 10
        : null;
      return out;
    }, {}),
    /**
     * A BUSINESS CANNOT BE FAILED. It can only do better or worse than before.
     *
     * `passed` compared the day against a fixed target of $130-465 on days that
     * net thousands, and printed "Not enough in the till." over a hotel that had
     * made money. That is a level objective wearing a hotel's clothes. The
     * targets stay on the config because the ladder still reads them; nothing
     * judges the player with them any more.
     */
    passed: true,
  };
}






