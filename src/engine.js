/**
 * WHAT THE FRONT DESK DOES WITH A BETTER ROOM THAN THE GUEST BOOKED.
 *
 * The operator's note, and the whole reason room views are modelled: "this can
 * sell a room higher than normal rate or just provide better satisfaction and
 * rating from normal reservations (if no other room is free or we are chasing
 * rating)."
 *
 * Both are real plays and neither is the right one in general, so this is a
 * standing policy the player sets rather than a prompt on every arrival. A
 * prompt per check-in would be correct and unplayable on a phone; a policy is
 * the same decision made once, which is also how a real front office runs it -
 * you brief the desk, you do not stand behind them.
 *
 *   PROTECT   Tightest fit. Honour the booking, keep the good rooms for people
 *             who will pay for them. The professional default.
 *   SELL      Offer the upgrade at the desk. Most guests say no; the ones who
 *             say yes are pure margin on a room that was going to sit empty.
 *   DELIGHT   Hand it over. Costs you the premium, buys satisfaction and the
 *             reviews that let you raise the rate on everything.
 */
export const UPSELL_POLICY = {
  PROTECT: "protect",
  SELL: "sell",
  DELIGHT: "delight",
};

/**
 * How readily a guest takes the upgrade when it is offered.
 *
 * Falls with how much is being asked relative to the room they booked, because
 * that is what an impulse purchase at a desk actually looks like. Nobody takes
 * it at any price, and a bargain is close to a coin flip.
 */
export const UPSELL_BASE_ACCEPTANCE = 0.34;

export function upsellAcceptance(price, bookedTotal) {
  const ask = price / Math.max(1, bookedTotal);
  return clamp(UPSELL_BASE_ACCEPTANCE + 0.30 * (0.35 - ask), 0.06, 0.62);
}

/** Satisfaction a free upgrade buys, per 10% of grade handed over. */
export const UPGRADE_DELIGHT = 7;

/**
 * The mean value of the rooms in a house, used to normalise grade pricing.
 *
 * Returns 1 for a house with no floorplan, which is what makes the graded model
 * a strict superset of the flat one: with no rooms to grade, every room is worth
 * exactly the rate the player set, and nothing about the old balance moves.
 */
export function houseAverageMultiplier(house) {
  if (!house || house.length === 0) return 1;
  const total = house.reduce((sum, room) => sum + room.rateMultiplier, 0);
  return total / house.length;
}

/**
 * What THIS room charges against the rate the player set.
 *
 * A sea-view suite is not worth the same as an interior single, and the rate
 * screen sets one number for the house. So the number the player sets is the
 * rate of an AVERAGE room, and every actual room is priced relative to it. That
 * is how a real rate sheet works - you publish a lead-in rate and the better
 * rooms carry a supplement.
 */
export function roomGradeFactor(shift, room) {
  if (!room || !room.entity) return 1;
  const average = shift.houseAverage || 1;
  return room.entity.rateMultiplier / average;
}

/**
 * The type a guest books, drawn from the types the house ACTUALLY has.
 *
 * Nobody books a suite at a hotel with no suites, and a house that is mostly
 * twins should mostly take twin bookings. Weighted by how common each type is
 * in the building, which keeps the book plausible without a separate table.
 */
export function bookedTypeFor(house, roll) {
  const counts = {};
  for (const room of house) counts[room.type] = (counts[room.type] ?? 0) + 1;
  const table = Object.entries(counts).map(([type, n]) => ({ type, weight: n }));
  const total = table.reduce((sum, row) => sum + row.weight, 0);
  let r = roll * total;
  for (const row of table) {
    r -= row.weight;
    if (r <= 0) return row.type;
  }
  return table.length ? table[table.length - 1].type : null;
}

/** Weighted pick from a [{weight}] table using the shift's seeded stream. */
function pickWeighted(shift, table) {
  const total = table.reduce((sum, row) => sum + row.weight, 0);
  let roll = nextRandom(shift) * total;
  for (const row of table) {
    roll -= row.weight;
    if (roll <= 0) return row;
  }
  return table[table.length - 1];
}

/**
 * RUNNING COSTS - what the work itself consumes.
 *
 * A turned room is not free labour with a free result. It costs a set of linen
 * through a laundry, and it costs the amenities that go back into the room:
 * soap, shampoo, paper, the tea tray. Reception burns key cards and registration
 * cards; maintenance burns parts. Wages were already modelled; this is the OTHER
 * half of a hotel's cost base, and without it occupancy is pure profit and the
 * only reason to build anything is a star.
 *
 * THE LAUNDRY IS THE POINT. Sending linen out is a per-kilo contract that scales
 * with every single room you turn - the busier you are, the more it costs. Owning
 * a laundry replaces that with detergent, water and power against a machine you
 * have already paid for. So the laundry is not a star requirement you tick off;
 * it is the moment a variable cost becomes a fixed one, and it pays back faster
 * the fuller you run. That is the real decision a hotelier makes.
 */
export const SUPPLY = {
  LINEN: "linen",        // sheets and towels - out to a contractor, or washed here
  AMENITIES: "amenities",// soap, shampoo, paper, the tray - back into the room
  DESK: "desk",          // key cards, registration cards, the welcome note
  PARTS: "parts",        // what maintenance actually fits
};

/** Outsourced per room turn, against doing it yourself once a laundry is built. */
export const LINEN_COST = { outsourced: 9, inHouse: 2.5 };

/**
 * Amenities scale with class, because they are the class. A 1-star's wrapped
 * soap and a 5-star's toiletries are the same line on the same invoice and an
 * order of magnitude apart, which is part of why charging more is not free money.
 */
export const AMENITY_COST_BY_CLASS = { 1: 1.5, 2: 2.25, 3: 3.5, 4: 6, 5: 10 };

export const DESK_COST = 0.6;
export const PARTS_COST = 12;

